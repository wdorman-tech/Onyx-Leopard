"""End-of-run CEO post-mortem reports.

Produced once per company when a `MultiCompanySimV2` finishes (whether by
hitting `max_ticks`, going all-dead, or any other terminal condition).
Each report is a stance-aware narrative of the company's run: what the CEO
was trying to do, how it went, and what they would call out as the
inflection points. Survivors and casualties both get one — the user wants
the framing the same way regardless of outcome.

Design contract:

  * NOT part of the replay-determinism contract. Reports are derived
    end-state artifacts, not decisions the engine consumes. They can be
    regenerated by re-running the agent over the same final state +
    decision log without affecting the sim outcome. So we deliberately
    do NOT go through `replay_or_call` or write to the transcript.
  * Best-effort. If the API key is missing, the LLM call fails, or the
    cost ceiling would be exceeded, we fall back to a heuristic report
    derived from final state alone. The sim user always gets a report,
    just sometimes a thinner one.
  * Haiku 4.5 by default. One call per company at end-of-run is bounded
    and cheap; Sonnet is reserved for in-loop strategic decisions where
    capability actually moves the needle.
  * Forced tool-use for structured output, same pattern the orchestrator
    uses — schema with `additionalProperties: false` makes the response
    shape unbreakable.
"""

from __future__ import annotations

import json
import logging
import os
import re
from typing import TYPE_CHECKING, Any

from anthropic import AsyncAnthropic
from pydantic import BaseModel, ConfigDict, Field, ValidationError

from src.simulation.replay import CostTracker

if TYPE_CHECKING:
    from src.simulation.unified_v2 import CompanyAgentV2

log = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Tunables
# ---------------------------------------------------------------------------

#: Pinned Haiku model id (matches `replay.MODEL_PRICING` key).
POST_MORTEM_MODEL_ID: str = "claude-haiku-4-5"

#: Output token budget. The schema constrains shape; the model decides
#: how much prose to put in each string field. 1024 is generous for one
#: short paragraph per field + a 5-item key_decisions list.
POST_MORTEM_MAX_TOKENS: int = 1024

#: Predicted in/out token envelopes for the cost-tracker preflight. These
#: are upper bounds — the call rarely hits them, but the preflight protects
#: the per-sim USD ceiling from being blown by a runaway prompt.
POST_MORTEM_PREDICTED_INPUT_TOKENS: int = 4000
POST_MORTEM_PREDICTED_OUTPUT_TOKENS: int = 800

#: How many decisions from the full log to surface in the prompt. The full
#: log can be hundreds of entries; the model doesn't need every one — a
#: representative sample bounded at both ends keeps the prompt small
#: without losing the run's arc.
DECISIONS_HEAD_TAIL_LEN: int = 12


# ---------------------------------------------------------------------------
# CEOReport — public contract (matches frontend/src/types/unified.ts)
# ---------------------------------------------------------------------------


class CEOReport(BaseModel):
    """End-of-run reflection from one company's CEO. Shape matches the
    frontend type `CEOReport` in `frontend/src/types/unified.ts` so the
    SSE payload can be consumed by the existing dashboard modal verbatim.
    """

    model_config = ConfigDict(extra="forbid")

    #: Stable per-company identifier. Lets the frontend match a report to
    #: its agent panel by id instead of by `company_name`, which can
    #: collide in identical-start mode (every company shares `seed.name`).
    company_id: str = Field(..., min_length=1)
    company_name: str = Field(..., min_length=1)
    strategy: str = Field(..., min_length=1)
    performance_summary: str = Field(..., min_length=1)
    what_went_well: str = Field(..., min_length=1)
    what_went_wrong: str = Field(..., min_length=1)
    key_decisions: list[str] = Field(default_factory=list)
    final_assessment: str = Field(..., min_length=1)


# ---------------------------------------------------------------------------
# Anthropic tool-use schema — structurally forbids extra fields, matches
# `CEOReport` exactly. The agent forces `tool_choice` so the model cannot
# emit free-form text or skip required keys.
# ---------------------------------------------------------------------------


_REPORT_TOOL: dict[str, Any] = {
    "name": "submit_ceo_report",
    "description": (
        "Submit your end-of-run reflection on this company. You MUST call "
        "this tool exactly once and populate every required field."
    ),
    "input_schema": {
        "type": "object",
        "additionalProperties": False,
        "required": [
            "performance_summary",
            "what_went_well",
            "what_went_wrong",
            "key_decisions",
            "final_assessment",
        ],
        "properties": {
            "performance_summary": {
                "type": "string",
                "minLength": 1,
                "description": (
                    "2-4 sentences summarizing the company's overall arc — "
                    "starting position, trajectory, final state."
                ),
            },
            "what_went_well": {
                "type": "string",
                "minLength": 1,
                "description": (
                    "Concrete moves or conditions that worked. Cite specific "
                    "decisions or metrics where possible."
                ),
            },
            "what_went_wrong": {
                "type": "string",
                "minLength": 1,
                "description": (
                    "Concrete moves, missed signals, or conditions that "
                    "hurt the company. Honest, not performative."
                ),
            },
            "key_decisions": {
                "type": "array",
                "items": {"type": "string"},
                "description": (
                    "3-6 inflection points across the run, each a single "
                    "short sentence (e.g. 'Day 47: hired CFO during cash "
                    "crunch — bought runway visibility')."
                ),
                "minItems": 1,
                "maxItems": 8,
            },
            "final_assessment": {
                "type": "string",
                "minLength": 1,
                "description": (
                    "1-2 sentence verdict from the CEO's perspective. "
                    "Survivors should reflect on whether the position is "
                    "defensible; casualties should name the proximate cause."
                ),
            },
        },
    },
}


# ---------------------------------------------------------------------------
# Drift-tolerant normalization helpers
# ---------------------------------------------------------------------------

#: Tags Haiku has been observed to wrap decision items in. Order matters: we
#: try multi-char tags first so a `<item>` doesn't get partially matched.
_ITEM_TAGS: tuple[str, ...] = ("<item>", "</item>", "<li>", "</li>")


def _strip_markup(s: str) -> str:
    """Remove the wrapper tags + leading/trailing whitespace from one item."""
    out = s
    for tag in _ITEM_TAGS:
        out = out.replace(tag, "")
    return out.strip()


def _split_decision_string(blob: str) -> list[str]:
    """Best-effort split of a string-shaped `key_decisions` payload.

    Tries in order:
      1. Split on `<item>...</item>` / `<li>...</li>` block pairs.
      2. Fall back to splitting on newlines (the model sometimes ships
         bullets-as-lines).

    Empty items are dropped. The result is always a list; pathological
    inputs that contain no boundary marker return the entire blob as one
    decision, which is still better than failing validation outright.
    """
    matches = re.findall(r"<(?:item|li)>(.*?)</(?:item|li)>", blob, re.DOTALL)
    if matches:
        return [m.strip() for m in matches if m.strip()]
    # Fallback: newline-delimited bullets, stripped of stray tags.
    lines = [_strip_markup(line) for line in blob.splitlines()]
    lines = [line for line in lines if line]
    if lines:
        return lines
    cleaned = _strip_markup(blob)
    return [cleaned] if cleaned else []


# ---------------------------------------------------------------------------
# PostMortemAgent
# ---------------------------------------------------------------------------


def _get_client() -> AsyncAnthropic:
    """Build an AsyncAnthropic client from env credentials."""
    return AsyncAnthropic()  # reads ANTHROPIC_API_KEY


class PostMortemAgent:
    """Generates end-of-run CEO reports.

    One instance per simulation is enough — `generate()` is a pure function
    of the company state passed in. The agent does NOT hold per-company
    state.
    """

    def __init__(
        self,
        *,
        cost_tracker: CostTracker | None = None,
        client: AsyncAnthropic | None = None,
    ) -> None:
        self.cost_tracker: CostTracker | None = cost_tracker
        self._client: AsyncAnthropic | None = client

    # -- Public API -----------------------------------------------------

    async def generate(self, company: CompanyAgentV2) -> CEOReport:
        """Produce a CEOReport for one company.

        Best-effort: API failures, cost-ceiling skips, and missing API keys
        all fall back to `_heuristic_report` so the caller always gets a
        report. The CEO's voice is preserved when the LLM path is taken;
        the heuristic path is plain prose.
        """
        # No API key → heuristic only. The Anthropic SDK reads the env var
        # lazily; checking here lets us skip the network round-trip entirely
        # when we know there is no key configured.
        if not os.getenv("ANTHROPIC_API_KEY"):
            log.info(
                "post-mortem: ANTHROPIC_API_KEY unset, falling back to "
                "heuristic report for company=%s",
                company.company_id,
            )
            return self._heuristic_report(company)

        # Cost preflight — skip the LLM if it would push past the ceiling.
        if self.cost_tracker is not None and self.cost_tracker.would_exceed(
            POST_MORTEM_PREDICTED_INPUT_TOKENS,
            POST_MORTEM_PREDICTED_OUTPUT_TOKENS,
            POST_MORTEM_MODEL_ID,
        ):
            log.info(
                "post-mortem: cost ceiling would be exceeded, falling back "
                "to heuristic for company=%s",
                company.company_id,
            )
            return self._heuristic_report(company)

        try:
            return await self._llm_report(company)
        except Exception as exc:
            # Best-effort contract: any failure (transport, parse, schema)
            # logs and falls back. The user always gets a report.
            log.warning(
                "post-mortem LLM call failed for company=%s: %s — using "
                "heuristic fallback",
                company.company_id,
                exc,
            )
            return self._heuristic_report(company)

    # -- LLM path ------------------------------------------------------

    async def _llm_report(self, company: CompanyAgentV2) -> CEOReport:
        client = self._client if self._client is not None else _get_client()
        system_prompt = self._build_system_prompt(company)
        user_prompt = self._build_user_prompt(company)

        response = await client.messages.create(
            model=POST_MORTEM_MODEL_ID,
            max_tokens=POST_MORTEM_MAX_TOKENS,
            system=system_prompt,
            messages=[{"role": "user", "content": user_prompt}],
            tools=[_REPORT_TOOL],
            tool_choice={"type": "tool", "name": _REPORT_TOOL["name"]},
        )

        tool_block = next(
            (b for b in response.content if getattr(b, "type", None) == "tool_use"),
            None,
        )
        if tool_block is None:
            raise ValueError(
                "Expected tool_use block in response (tool_choice was forced); "
                f"got blocks: {[getattr(b, 'type', '?') for b in response.content]!r}"
            )
        data = dict(tool_block.input)

        # Record cost against the shared tracker. If it would overflow we
        # absorb the error — the post-mortem already produced a usable
        # response and aborting now would just lose that work.
        usage = getattr(response, "usage", None)
        in_tok = int(getattr(usage, "input_tokens", 0)) if usage else 0
        out_tok = int(getattr(usage, "output_tokens", 0)) if usage else 0
        if self.cost_tracker is not None:
            try:
                self.cost_tracker.record(in_tok, out_tok, POST_MORTEM_MODEL_ID)
            except Exception as exc:
                log.debug(
                    "post-mortem cost record overflowed (non-fatal): %s", exc
                )

        # Schema fields the tool does NOT emit (company_id, company_name,
        # strategy) come from the locked seed/stance/id — they're not the
        # model's to invent, and tying them to the source prevents drift.
        data["company_id"] = company.company_id
        data["company_name"] = company.seed.name
        data["strategy"] = company.stance.archetype

        # Normalize Haiku-style drift before Pydantic validation.
        # Observed live: model occasionally returns key_decisions as a
        # newline-separated string with `<item>` / `<li>` markup, and/or
        # omits final_assessment. Coerce these to the schema rather than
        # failing the whole report (which would drop a paragraph of real
        # CEO-voice content for a parsing technicality).
        data = self._normalize_llm_payload(data)

        try:
            return CEOReport(**data)
        except ValidationError as exc:
            raise ValueError(f"CEOReport schema mismatch: {exc.errors()}") from exc

    @staticmethod
    def _normalize_llm_payload(data: dict[str, Any]) -> dict[str, Any]:
        """Coerce common Haiku drift back to the CEOReport schema.

        Two observed failure modes (validated against real production runs):

        1. ``key_decisions`` arrives as a string with ``<item>...</item>``
           or ``<li>...</li>`` blocks, or as newline-delimited bullets.
           Split it into a list[str].

        2. ``final_assessment`` is missing entirely. Synthesize from the
           tail of ``performance_summary`` so the report still ships
           something coherent.
        """
        # 1. key_decisions string → list[str]
        kd = data.get("key_decisions")
        if isinstance(kd, str):
            data["key_decisions"] = _split_decision_string(kd)
        elif isinstance(kd, list):
            # Defensively strip any markup the model embedded inside a
            # legitimately-list element (e.g. "<li>Day 7: ...</li>").
            data["key_decisions"] = [_strip_markup(str(x)) for x in kd if str(x).strip()]

        # 2. final_assessment missing → synthesize from performance_summary
        if not data.get("final_assessment"):
            summary = (data.get("performance_summary") or "").strip()
            # Use the last sentence of the summary as a stand-in. If the
            # summary itself is empty, ship a generic line — the report is
            # still useful to the user even if the model under-delivered
            # this field.
            sentences = [s.strip() for s in summary.split(".") if s.strip()]
            data["final_assessment"] = (
                sentences[-1] + "." if sentences
                else "End-of-run assessment unavailable."
            )
        return data

    # -- Heuristic fallback --------------------------------------------

    def _heuristic_report(self, company: CompanyAgentV2) -> CEOReport:
        """No-LLM report. Used when there's no API key, the cost ceiling
        is exhausted, or the LLM call failed. Plain prose derived from
        final state — useful but lacks the CEO voice."""
        seed = company.seed
        stance = company.stance
        alive = company.alive
        cash = company.cash
        revenue = company.monthly_revenue
        employees = self._headcount(company)
        decisions_n = len(company.full_decision_log)

        survival_clause = (
            f"survived the run with ${cash:,.0f} cash and "
            f"${revenue:,.0f}/mo recurring revenue"
            if alive
            else f"went bankrupt; final cash position ${cash:,.0f}"
        )
        summary = (
            f"{seed.name} {survival_clause}. "
            f"Operated {employees} employees across "
            f"{decisions_n} CEO-level decisions over the run."
        )

        if alive and revenue > 0:
            went_well = (
                f"Maintained revenue at ${revenue:,.0f}/mo and avoided "
                "insolvency. Decision cadence was consistent with the "
                f"{stance.archetype} stance."
            )
        elif alive:
            went_well = (
                f"Stayed solvent on a cash position of ${cash:,.0f} "
                "despite operational headwinds."
            )
        else:
            went_well = (
                f"Built initial momentum — reached "
                f"${revenue:,.0f}/mo revenue before insolvency."
            )

        if alive:
            went_wrong = (
                "No catastrophic failures observed in the recorded state. "
                "Granular post-mortem narrative requires the LLM path."
            )
        else:
            went_wrong = (
                f"Cash ran out before the model could stabilize unit "
                f"economics. Burn ultimately exceeded recurring revenue "
                f"of ${revenue:,.0f}/mo."
            )

        # Pull the first few and last few decisions verbatim as a thin
        # timeline. The LLM path produces curated highlights; this is the
        # honest "we don't have the model, here are the raw moves."
        key_decisions: list[str] = []
        head = company.full_decision_log[:3]
        tail = company.full_decision_log[-3:]
        for tick, decision in head + tail:
            reasoning = (decision.reasoning or "").strip()
            if reasoning:
                # Trim — heuristic line should be one row, not a paragraph.
                reasoning = reasoning[:140] + ("…" if len(reasoning) > 140 else "")
                key_decisions.append(f"Day {tick}: {reasoning}")
        if not key_decisions:
            key_decisions = ["No CEO-level decisions were recorded for this run."]

        final = (
            f"Survived the year — the {stance.archetype} stance "
            "produced a defensible position."
            if alive
            else f"Did not survive the year — the {stance.archetype} "
            "stance could not stabilize unit economics in time."
        )

        return CEOReport(
            company_id=company.company_id,
            company_name=seed.name,
            strategy=stance.archetype,
            performance_summary=summary,
            what_went_well=went_well,
            what_went_wrong=went_wrong,
            key_decisions=key_decisions,
            final_assessment=final,
        )

    # -- Prompt builders -----------------------------------------------

    def _build_system_prompt(self, company: CompanyAgentV2) -> str:
        stance = company.stance
        seed = company.seed
        return (
            f"You are {seed.name}'s CEO writing an end-of-run reflection. "
            f"Your stance: archetype={stance.archetype}, "
            f"risk_tolerance={stance.risk_tolerance:.2f}, "
            f"growth_obsession={stance.growth_obsession:.2f}, "
            f"quality_floor={stance.quality_floor:.2f}, "
            f"time_horizon={stance.time_horizon}, "
            f"voice=\"{stance.voice}\". "
            "Speak in first person, in your own voice. Be honest about "
            "what happened — survivors should acknowledge near-misses, "
            "casualties should name the cause without theatre. "
            "Call out concrete decisions and metrics. "
            "You MUST call the submit_ceo_report tool exactly once."
        )

    def _build_user_prompt(self, company: CompanyAgentV2) -> str:
        seed = company.seed
        payload = {
            "company": {
                "name": seed.name,
                "niche": seed.niche,
                "archetype": seed.archetype,
                "economics_model": seed.economics_model,
                "starting_cash": seed.starting_cash,
                "starting_employees": seed.starting_employees,
                "starting_price": seed.starting_price,
            },
            "final_state": {
                "alive": company.alive,
                "tick": company.tick,
                "cash": round(company.cash, 2),
                "monthly_revenue": round(company.monthly_revenue, 2),
                "daily_revenue": round(company.daily_revenue, 2),
                "daily_costs": round(company.daily_costs, 2),
                "market_share": round(company.market_share, 4),
                "satisfaction": round(company.satisfaction, 3),
                "capacity_utilization": round(company.capacity_utilization, 3),
                "employee_count": self._headcount(company),
                "spawned_nodes": dict(company.spawned_nodes),
                "consecutive_insolvent_ticks": company.consecutive_insolvent,
            },
            "decision_log_sample": self._summarize_decisions(company),
            "total_decisions": len(company.full_decision_log),
        }
        return json.dumps(payload, sort_keys=True, separators=(",", ":"))

    # -- Helpers --------------------------------------------------------

    @staticmethod
    def _headcount(company: CompanyAgentV2) -> int:
        # spawned_nodes is `node_key -> count`; the engine doesn't expose
        # a headcount property directly. Sum the counts as a usable proxy.
        return sum(company.spawned_nodes.values())

    @staticmethod
    def _summarize_decisions(company: CompanyAgentV2) -> list[dict[str, Any]]:
        log_ = company.full_decision_log
        if not log_:
            return []
        # Head + tail sample. For a 1-year run there are typically ~70
        # decisions — taking 12 from each end gives the model both the
        # opening posture and the closing maneuvers without flooding the
        # prompt with the middle.
        head = log_[:DECISIONS_HEAD_TAIL_LEN]
        tail = (
            log_[-DECISIONS_HEAD_TAIL_LEN:]
            if len(log_) > 2 * DECISIONS_HEAD_TAIL_LEN
            else []
        )
        merged = head + tail
        return [
            {
                "tick": tick,
                "tier": decision.tier,
                "spawn_nodes": list(decision.spawn_nodes),
                "retire_nodes": list(decision.retire_nodes),
                "adjust_params": dict(decision.adjust_params),
                "reasoning": (decision.reasoning or "")[:220],
            }
            for tick, decision in merged
        ]


